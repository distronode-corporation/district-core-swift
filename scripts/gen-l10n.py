#!/usr/bin/env python3
"""Generate DistrictL10n's catalogs and Swift from contracts/i18n/ and l10n/, or check
that what is committed is what they produce.

    python3 scripts/gen-l10n.py            # write everything below
    python3 scripts/gen-l10n.py --check    # fail if any of it is stale (CI)

What it writes:

  l10n/api_errors.toml      one entry per error code in contracts/i18n/api-errors.json
                            (two for a code whose sentence lists items: with and
                            without the list)
  l10n/wire.toml            one entry per labelled value in
                            contracts/i18n/wire-vocabulary.json, its server
                            placeholders, and the generic label for a value this build
                            does not know
  Sources/DistrictL10n/Generated/Strings.swift
                            the accessors of every catalog, by `tools/l10n/l10n.py gen
                            --backend swift` (one file, one runtime: the hand-written
                            `L10nRuntime`)
  Sources/DistrictL10n/Generated/ApiErrorTable.swift, WireTable.swift
                            code and value to accessor
  Tests/DistrictL10nTests/Generated/AccessorTests.swift
                            every accessor and table row called in both languages and
                            held to its catalog's text

l10n/core.toml and l10n/countries.toml are written by hand. The two catalogs written
here keep any `fr`, `state` and the other translation fields an entry already has, as
long as its English has not changed: `l10n.py import` writes French into them like into
any other catalog, and a regeneration does not lose it.

The contracts are copied from the monorepo unchanged and the tools by `l10n.py vendor`;
this script reads both and changes neither. Python 3.11 or newer, standard library only.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOGS = ROOT / "l10n"
GENERATED = ROOT / "Sources" / "DistrictL10n" / "Generated"
TESTS = ROOT / "Tests" / "DistrictL10nTests" / "Generated"
CONTRACTS = ROOT / "contracts" / "i18n"
TOOL = ROOT / "tools" / "l10n" / "l10n.py"

# Every catalog, in the order the generator reads them. CI's `l10n.py check` names the
# same files in the same order, with the same options.
NAMES = ("core", "countries", "api_errors", "wire")
GEN_OPTS = ("--opt", "runtime=external", "--opt", "access=package", "--opt", "int_fmt=L10nFormat.count")
STRINGS = GENERATED / "Strings.swift"

# The fields a regeneration carries over from an entry whose English is unchanged.
KEPT = ("fr", "state", "same_ok", "fr_variant", "waive", "max", "id", "fixed")

HEADER = "// @generated by scripts/gen-l10n.py from {source}. Do not edit; run the script."
NBSP = "\u00a0"


def load_tool():
    spec = importlib.util.spec_from_file_location("l10n", TOOL)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


L10N = load_tool()


def slug(text: str) -> str:
    """A key segment: lower case, runs of anything else as one underscore."""
    s = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    return s if re.match(r"[a-z]", s) else f"v_{s}"


def snake(name: str) -> str:
    """`callStatus` -> `call_status`."""
    return re.sub(r"(?<!^)([A-Z])", r"_\1", name).lower()


def humanize(raw: str) -> str:
    """What the website shows for a value with no label of its own: hyphens and
    underscores as spaces, the first letter capitalized."""
    words = raw.strip().replace("-", " ").replace("_", " ")
    return words[:1].upper() + words[1:]


def swift_str(text: str) -> str:
    return '"' + L10N.escape_c_like(text, "swift") + '"'


def member(key: str, catalog) -> str:
    """The Swift accessor of `key`, `Enum.member`."""
    return ".".join(L10N.swift_name(catalog.entries[key]))


# Catalogs from the contracts.


def entry(en, ctx, screen, tier, note, args=None) -> dict:
    fields = {"en": en, "ctx": ctx, "screen": screen, "tier": tier}
    if args:
        fields["args"] = args
    fields["note"] = note
    return fields


def api_error_key(code: str) -> str:
    # Some codes differ only by case (`forbidden`, `FORBIDDEN`); key segments are lower
    # case, so the upper-case ones get their own group.
    return f"api_error.{slug(code)}" if code == code.lower() else f"api_error_caps.{slug(code)}"


def api_error_entries(doc: dict) -> tuple[dict, list[tuple[str, str, str | None]]]:
    """The catalog's entries by key, and (code, key, key without the list) per code."""
    placeholder = doc["itemsPlaceholder"]
    entries: dict[str, dict] = {}
    table = []
    for code, sentence in doc["codes"].items():
        key = api_error_key(code)
        note = (
            f"Shown on any screen when the service refuses a request with the error code "
            f"`{code}`, in place of the service's own English."
        )
        without = None
        if "listField" in sentence:
            assert placeholder in sentence["en"], code
            entries[key] = entry(
                sentence["en"], "error", "api_error", "T2",
                note + " {items} is the list of what the refusal names (field names or region "
                "names), joined with commas.",
                {"items": "str"},
            )
            without = f"{key}_without_list"
            entries[without] = entry(
                sentence["enWithoutList"], "error", "api_error", "T2",
                note + " This form is used when the service named nothing to list.",
            )
        else:
            entries[key] = entry(sentence["en"], "error", "api_error", "T2", note)
        table.append((code, key, without))
    return entries, table


def wire_entries(doc: dict):
    """The catalog's entries by key; (category, value, key) per labelled value; (category,
    fallback key) per category with a fallback of its own; (region, long key) per region;
    (placeholder text, key); and the categories in contract order."""
    entries: dict[str, dict] = {}
    labels, fallbacks, longs, placeholders = [], [], [], []
    for name, category in doc["categories"].items():
        group = snake(name)
        for value in category["values"]:
            key = f"wire.{group}.{slug(value['value'])}"
            en = value["en"] if value["en"] is not None else humanize(value["value"])
            note = f"A label for the stored value `{value['value']}` of {name}. {category['description']}"
            if value["en"] is None:
                note += " The service has no label for it; the English is the value as the website shows it."
            entries[key] = entry(en, "label", f"wire {group}", "T3", note)
            labels.append((name, value["value"], key))
            if "enLong" in value:
                long_key = f"wire.{group}_long.{slug(value['value'])}"
                entries[long_key] = entry(
                    value["enLong"], "label", f"wire {group}", "T3",
                    f"The long name of the data region `{value['value']}`, naming its datacenter.",
                )
                longs.append((value["value"], long_key))
        if "fallback" in category:
            key = f"wire.{group}.fallback"
            entries[key] = entry(
                category["fallback"]["en"], "label", f"wire {group}", "T3",
                f"The label for a value of {name} this build does not know, or none.",
            )
            fallbacks.append((name, key))
    entries["wire.generic.other"] = entry(
        "Other", "label", "wire generic", "T3",
        "The label for a stored status, type or outcome this version of the app has no label "
        "for. Never the stored English itself.",
    )
    for placeholder in doc["placeholders"]:
        value = placeholder["value"]
        # ⚠️ The one placeholder holding an em dash is left out: this repository's dash
        # rule forbids the character in Sources/, and the generator writes it raw.
        # `CallNarrative.placeholders` still recognises it (spelled as an escape).
        if "\u2014" in value:
            continue
        key = f"wire.placeholder.{slug(value)}"
        entries[key] = entry(
            value, "label", "wire placeholder", "T3",
            f"Text the service stores or sends in English in place of a real value, in "
            f"{'; '.join(placeholder['fields'])}. Shown where that value is shown.",
        )
        placeholders.append((value, key))
    return entries, labels, fallbacks, longs, placeholders, list(doc["categories"])


def render_catalog(name: str, entries: dict, previous: Path) -> str:
    """The canonical text of a generated catalog, keeping the translation fields of every
    entry whose English is unchanged."""
    old = {}
    if previous.is_file():
        old = {e.key: e.fields for e in L10N.load_catalog(previous).entries.values()}
    data: dict = {"meta": {"catalog": name, "platform": "swift", "apple": True}}
    for key, fields in entries.items():
        fields = dict(fields)
        before = old.get(key)
        if before is not None and before.get("en") == fields["en"]:
            for field in KEPT:
                if field in before:
                    fields[field] = before[field]
        node = data
        *parents, last = key.split(".")
        for part in parents:
            node = node.setdefault(part, {})
        node[last] = fields
    cat = L10N.catalog_from_data(previous, data)
    return L10N.emit_catalog(cat)


# Swift tables.


def api_error_table(table, cat) -> str:
    lines = [HEADER.format(source="contracts/i18n/api-errors.json"), "// swiftlint:disable all", ""]
    lines.append("/// Error code to its catalog sentence.")
    lines.append("enum ApiErrorTable {")
    lines.append("    /// The sentence for `code` in the active language, with `items` where it lists")
    lines.append("    /// them, or nil for a code the contract does not have.")
    lines.append("    static func sentence(_ code: String, items: String?) -> String? {")
    lines.append("        switch code {")
    for code, key, without in table:
        if without is None:
            lines.append(f"        case {swift_str(code)}: return {member(key, cat)}")
        else:
            lines.append(f"        case {swift_str(code)}:")
            lines.append(f"            guard let items else {{ return {member(without, cat)} }}")
            lines.append(f"            return {member(key, cat)}(items)")
    lines.append("        default: return nil")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def wire_table(labels, fallbacks, longs, placeholders, categories, cat) -> str:
    lines = [HEADER.format(source="contracts/i18n/wire-vocabulary.json"), "// swiftlint:disable all", ""]
    lines.append("/// An enumerated wire value a screen shows, by the field it arrives in.")
    lines.append("/// `contracts/i18n/wire-vocabulary.json` describes each one.")
    lines.append("public enum WireCategory: String, CaseIterable, Sendable {")
    for name in categories:
        lines.append(f"    case {name}")
    lines.append("}")
    lines.append("")
    lines.append("/// Wire value to its catalog label.")
    lines.append("enum WireTable {")
    lines.append("    /// The label of `value` (trimmed, in lower case) in `category`, or nil for a")
    lines.append("    /// value the vocabulary does not have.")
    lines.append("    static func label(_ category: WireCategory, _ value: String) -> String? {")
    lines.append("        switch (category, value) {")
    for name, value, key in labels:
        lines.append(f"        case (.{name}, {swift_str(value.strip().lower())}): {member(key, cat)}")
    lines.append("        default: nil")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// The category's own label for a value it does not know, when it has one.")
    lines.append("    static func fallback(_ category: WireCategory) -> String? {")
    lines.append("        switch category {")
    for name, key in fallbacks:
        lines.append(f"        case .{name}: {member(key, cat)}")
    lines.append("        default: nil")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// A region's long name, or nil for a region the vocabulary does not have.")
    lines.append("    static func regionLong(_ value: String) -> String? {")
    lines.append("        switch value {")
    for value, key in longs:
        lines.append(f"        case {swift_str(value.lower())}: {member(key, cat)}")
    lines.append("        default: nil")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// The label of a placeholder the service stores or sends, exactly as it")
    lines.append("    /// sends it, or nil for any other text.")
    lines.append("    static func placeholder(_ text: String) -> String? {")
    lines.append("        switch text {")
    for value, key in placeholders:
        lines.append(f"        case {swift_str(value)}: {member(key, cat)}")
    lines.append("        default: nil")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


# The accessor test.


def integer(locale: str, n: int) -> str:
    """L10nFormat.count: plain digits in English, grouped by no-break spaces in French."""
    digits = str(abs(n))
    if locale == "frCA":
        digits = "".join((NBSP if i and (len(digits) - i) % 3 == 0 else "") + d for i, d in enumerate(digits))
    return ("-" if n < 0 else "") + digits


def expected(entry, locale: str, lang: str, forms, values: dict) -> str:
    """What the accessor returns in `locale` for `values`, where `lang`'s plural rules
    choose among `forms`."""
    if isinstance(forms, dict):
        n = values[entry.selector()]
        text = forms.get(L10N.plural_category(lang, n), forms["other"])
    else:
        text = forms
    out = []
    for kind, part in L10N.parse_text(text)[0]:
        if kind == "lit":
            out.append(part)
        elif isinstance(values[part], int):
            out.append(integer(locale, values[part]))
        else:
            out.append(values[part])
    return "".join(out)


def call(entry, values: dict) -> str:
    name = ".".join(L10N.swift_name(entry))
    if not entry.args:
        return name
    args = [str(values[n]) if kind == "int" else swift_str(values[n]) for n, kind in entry.args.items()]
    return f"{name}({', '.join(args)})"


def accessor_test(cats: dict, error_table, wire) -> str:
    labels, fallbacks, longs, placeholders, categories = wire
    lines = [HEADER.format(source="the catalogs in l10n/ and contracts/i18n/"), "// swiftlint:disable all", ""]
    lines.append("@testable import DistrictL10n")
    lines.append("import XCTest")
    lines.append("")
    lines.append("/// Every accessor, error code and wire value, in both languages, held to the text")
    lines.append("/// its catalog gives it. Until an entry has French, its French is its English.")
    lines.append("final class GeneratedAccessorTests: XCTestCase {")
    for name in NAMES:
        cat = cats[name]
        method = "".join(p.capitalize() for p in name.split("_"))
        lines.append(f"    func testEvery{method}AccessorSaysWhatItsCatalogSays() {{")
        for locale in ("en", "frCA"):
            lines.append(f"        L10nRuntime.withLocale(.{locale}) {{")
            for e in sorted(cat.entries.values(), key=lambda e: e.segs):
                counts = [0, 1, 2, 1_204, 1_000_000] if e.plural else [1_204]
                for n in counts:
                    values = {a: (n if kind == "int" else "{" + a + "}") for a, kind in e.args.items()}
                    if locale == "en":
                        text = expected(e, "en", "en", e.en, values)
                    else:
                        lang, forms = ("fr", e.fr) if e.fr is not None else ("en", e.en)
                        text = expected(e, "frCA", lang, forms, values)
                    lines.append(f"            XCTAssertEqual({call(e, values)}, {swift_str(text)})")
                    if not e.args:
                        break
            lines.append("        }")
        lines.append("    }")
        lines.append("")
    errors = cats["api_errors"]
    lines.append("    func testEveryErrorCodeHasItsSentence() {")
    lines.append("        L10nRuntime.withLocale(.en) {")
    for code, key, without in error_table:
        e = errors.entries[key]
        if without is None:
            lines.append(f"            XCTAssertEqual(ApiErrorTable.sentence({swift_str(code)}, items: nil), {swift_str(e.en)})")
        else:
            listed = e.en.replace("{items}", "a, b")
            lines.append(
                f"            XCTAssertEqual(ApiErrorTable.sentence({swift_str(code)}, items: \"a, b\"), {swift_str(listed)})"
            )
            plain = errors.entries[without].en
            lines.append(f"            XCTAssertEqual(ApiErrorTable.sentence({swift_str(code)}, items: nil), {swift_str(plain)})")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    wire_cat = cats["wire"]
    lines.append("    func testEveryWireValueHasItsLabel() {")
    lines.append("        L10nRuntime.withLocale(.en) {")
    for name, value, key in labels:
        lines.append(
            f"            XCTAssertEqual(WireTable.label(.{name}, {swift_str(value.strip().lower())}), "
            f"{swift_str(wire_cat.entries[key].en)})"
        )
    for name, key in fallbacks:
        lines.append(f"            XCTAssertEqual(WireTable.fallback(.{name}), {swift_str(wire_cat.entries[key].en)})")
    for value, key in longs:
        lines.append(f"            XCTAssertEqual(WireTable.regionLong({swift_str(value.lower())}), {swift_str(wire_cat.entries[key].en)})")
    for value, key in placeholders:
        lines.append(f"            XCTAssertEqual(WireTable.placeholder({swift_str(value)}), {swift_str(wire_cat.entries[key].en)})")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    func testFrenchIsCompleteOnlyWhenEveryEntryHasIt() {")
    complete = all(e.fr is not None or e.fixed for c in cats.values() for e in c.entries.values())
    lines.append(f"        XCTAssertEqual(L10nRuntime.isFrenchComplete, {'true' if complete else 'false'})")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


# Driving it.


def gen_swift(paths: list[Path]) -> str:
    """The accessors l10n.py generates for the catalogs together."""
    with tempfile.TemporaryDirectory() as tmp:
        target = Path(tmp) / STRINGS.name
        subprocess.run(
            [sys.executable, str(TOOL), "gen", "--backend", "swift", *map(str, paths), "--out", str(target), *GEN_OPTS],
            check=True, capture_output=True, text=True,
        )
        return target.read_text(encoding="utf-8")


def outputs() -> dict[Path, str]:
    errors_doc = json.loads((CONTRACTS / "api-errors.json").read_text(encoding="utf-8"))
    wire_doc = json.loads((CONTRACTS / "wire-vocabulary.json").read_text(encoding="utf-8"))
    errors, error_table = api_error_entries(errors_doc)
    wire, labels, fallbacks, longs, placeholders, categories = wire_entries(wire_doc)

    files: dict[Path, str] = {}
    files[CATALOGS / "api_errors.toml"] = render_catalog("api_errors", errors, CATALOGS / "api_errors.toml")
    files[CATALOGS / "wire.toml"] = render_catalog("wire", wire, CATALOGS / "wire.toml")

    with tempfile.TemporaryDirectory() as tmp:
        cats, staged = {}, []
        for name in NAMES:
            path = CATALOGS / f"{name}.toml"
            text = files.get(path)
            if text is None:
                text = path.read_text(encoding="utf-8")
            copy = Path(tmp) / f"{name}.toml"
            copy.write_text(text, encoding="utf-8")
            cats[name] = L10N.load_catalog(copy)
            staged.append(copy)
        files[STRINGS] = gen_swift(staged)
        files[GENERATED / "ApiErrorTable.swift"] = api_error_table(error_table, cats["api_errors"])
        files[GENERATED / "WireTable.swift"] = wire_table(labels, fallbacks, longs, placeholders, categories, cats["wire"])
        files[TESTS / "AccessorTests.swift"] = accessor_test(
            cats, error_table, (labels, fallbacks, longs, placeholders, categories)
        )
    return files


def check_catalogs() -> list[str]:
    """`l10n.py check` on the catalogs and their generated Swift: a stale or
    non-canonical file fails it."""
    done = subprocess.run(
        [sys.executable, str(TOOL), "check", *(str(CATALOGS / f"{n}.toml") for n in NAMES),
         "--gen", f"swift:{STRINGS}", *GEN_OPTS],
        capture_output=True, text=True,
    )
    return [] if done.returncode == 0 else [f"l10n.py check:\n{done.stdout}{done.stderr}"]


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if anything committed is stale")
    args = parser.parse_args(argv[1:])
    try:
        files = outputs()
    except subprocess.CalledProcessError as exc:
        print(f"gen-l10n: {' '.join(exc.cmd[:4])} failed:\n{exc.stdout}{exc.stderr}", file=sys.stderr)
        return 1
    except L10N.L10nError as exc:
        print("gen-l10n: " + "\n".join(exc.lines), file=sys.stderr)
        return 1
    stale = [path for path, text in files.items() if not path.is_file() or path.read_bytes() != text.encode("utf-8")]
    if args.check:
        problems = [f"{path.relative_to(ROOT)} is stale; run python3 scripts/gen-l10n.py" for path in stale]
        problems += check_catalogs()
        for problem in problems:
            print(f"gen-l10n: {problem}", file=sys.stderr)
        if not problems:
            print(f"gen-l10n: {len(files)} generated files are current")
        return 1 if problems else 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(files[path].encode("utf-8"))
        print(f"wrote {path.relative_to(ROOT)}")
    if not stale:
        print("gen-l10n: everything is current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
